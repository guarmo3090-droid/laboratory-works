#include <iostream>
#include <opencv2/opencv.hpp> // Заголовок для основних функцій OpenCV

int main() {
    // 1. Ініціалізація об'єкта VideoCapture для зчитування з камери.
    // Аргумент '0' зазвичай вказує на першу підключену камеру.
    cv::VideoCapture cap(0);

    // Перевірка, чи вдалося відкрити камеру
    if (!cap.isOpened()) {
        std::cerr << "Помилка: Не вдалося відкрити камеру." << std::endl;
        return -1;
    }

    // Створення об'єкта cv::Mat для зберігання кадру
    cv::Mat frame;

    // Нескінченний цикл для обробки відеопотоку
    while (true) {
        // 2. Зчитування нового кадру з камери.
        // '>>' це зручний оператор для cap.read(frame).
        cap >> frame;

        // Перевірка, чи вдалося зчитати кадр
        if (frame.empty()) {
            std::cerr << "Помилка: Пустий кадр з камери." << std::endl;
            break;
        }

        // --- 3. Малювання на кадрі ---

        // Отримання розмірів кадру
        int width = frame.cols;
        int height = frame.rows;

        // Малювання червоного кола в центрі кадру
        cv::circle(
            frame,                                // Зображення, на якому малюємо
            cv::Point(width / 2, height / 2),     // Координати центру (Point)
            50,                                   // Радіус
            cv::Scalar(0, 0, 255),                // Колір BGR (Blue, Green, Red) - тут червоний
            -1                                    // Товщина лінії (-1 означає заповнений круг)
        );

        // Додавання тексту на кадр
        cv::putText(
            frame,                                // Зображення, на якому малюємо
            "Live Stream + OpenCV",               // Текст
            cv::Point(10, 30),                    // Початкова точка тексту
            cv::FONT_HERSHEY_SIMPLEX,             // Тип шрифту
            0.7,                                  // Масштаб шрифту
            cv::Scalar(255, 255, 0),              // Колір BGR - тут жовто-блакитний (Cyan)
            2                                     // Товщина лінії
        );

        // --- 4. Виведення результату у вікно ---

        // Відображення обробленого кадру у вікні з назвою "Camera Feed"
        cv::imshow("Camera Feed", frame);

        // Очікування натискання клавіші протягом 1 мс.
        // Якщо натиснуто 'q' або 'Q', цикл завершується.
        if (cv::waitKey(1) == 'q' || cv::waitKey(1) == 'Q') {
            break;
        }
    }

    // 5. Звільнення об'єктів
    cap.release(); // Звільнення камери
    cv::destroyAllWindows(); // Закриття всіх вікон OpenCV

    return 0;
}
